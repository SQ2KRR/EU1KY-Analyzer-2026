int RU_FONT_Pobierz(uint32_t unicode, FONTS font, RU_FONT_GLIF_t *glif)
{
    int lewo = 0;
    int prawo = (int)(sizeof(ru_mapa) / sizeof(ru_mapa[0])) - 1;

    if (glif == NULL)
        return 0;
    /*
     * FONT_KAFEL ma komórkę 16 px, identyczną jak FONT_FRAN, i jest teraz
     * używany do tych samych przycisków paska akcji, które w wersji rosyjskiej
     * pokazują etykiety cyrylicą ("Пост.", "Свой", "Сохр." itd.). Bez tego
     * warunku RU_FONT_Pobierz zwracałby 0 dla FONT_KAFEL, a wywołujący spadłby
     * do FONT_ZnakBazowy, który cyrylicy nie rozpoznaje - efekt byłby pustym
     * lub błędnym znakiem zamiast litery. Traktujemy go więc jak FONT_FRAN
     * (mały zestaw, 16 px).
     */
    if (font != FONT_FRAN && font != FONT_FRANBIG && font != FONT_KAFEL)
        return 0;

    while (lewo <= prawo)
    {
        const int srodek = lewo + (prawo - lewo) / 2;
        const RU_FONT_MAPA_t *wpis = &ru_mapa[srodek];

        if (wpis->unicode == unicode)
        {
            if (font == FONT_FRANBIG)
            {
                glif->dane = &ru_font_duzy[wpis->offset_duzy];
                glif->szerokosc = wpis->szerokosc_duza;
                glif->wysokosc = 32U;
                glif->bajtow_na_wiersz = wpis->bajtow_duzy;
            }
            else
            {
                glif->dane = &ru_font_maly[wpis->offset_maly];
                glif->szerokosc = wpis->szerokosc_mala;
                glif->wysokosc = 16U;
                glif->bajtow_na_wiersz = wpis->bajtow_maly;
            }
            return 1;
        }

        if (wpis->unicode < unicode)
            lewo = srodek + 1;
        else
            prawo = srodek - 1;
    }
    return 0;
}
